    // Ключ подписи и пароли — в android/keystore.properties (не в git, шаблон — keystore.properties.example).
    // Без файла debug собирается как обычно, а release падает на проверке подписи.
    signingConfigs {
        create("release") {
            val propsFile = rootProject.file("keystore.properties")
            if (propsFile.exists()) {
                val props = Properties().apply { propsFile.inputStream().use { load(it) } }
                storeFile = file(props.getProperty("storeFile"))
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Эмулятор видит компьютер по адресу 10.0.2.2 (см. 02_ARCHITECTURE.md)
