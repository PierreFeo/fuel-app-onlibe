        }
        release {
            buildConfigField("String", "BASE_URL", "\"https://fuelapp.ru/api/v1/\"")
            signingConfig = signingConfigs.getByName("release")
            // R8 выключен: для kotlinx.serialization и Retrofit нужны keep-правила, без них
            // release может падать там, где debug работает (DECISIONS.md)
            optimization {
                enable = false
            }
        }
    }
